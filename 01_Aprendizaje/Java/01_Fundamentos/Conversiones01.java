public class Conversiones01 
{
    public static void main(String[] args)
    {
        double d = 19.99;
        int i = (int)d;

        int j = 10;
        double e = j;

        System.out.println("Valor de d como double: " + d + " como int: " + i);
        System.out.println("Valor de j como int: " + j + " como double: " + e);
    }
}
